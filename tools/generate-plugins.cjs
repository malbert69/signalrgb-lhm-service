const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'plugins', 'catalog.json'), 'utf8'));
const template = fs.readFileSync(path.join(root, 'ASUS_LHM_Temperatures.js'), 'utf8').replace(/\r\n/g, '\n');
const check = process.argv.includes('--check');
let written = 0;
const modelKeys = new Set();
const controllerIds = new Set();
const filenames = new Set();
const boardLiteral = template.match(/const BOARD = (\{[\s\S]*?\n\});\nconst SENSOR_DEFINITIONS/);
assert.ok(boardLiteral, 'root plugin board definition missing');
const rootBoard = JSON.parse(vm.runInNewContext('JSON.stringify(' + boardLiteral[1] + ')', {}, { timeout: 1000 }));
const installEntries = [{ path: 'ASUS_LHM_Temperatures.js', manufacturers: rootBoard.manufacturers, models: rootBoard.models || [rootBoard.model] }];
controllerIds.add(rootBoard.controllerId);
for (const manufacturer of rootBoard.manufacturers) for (const model of rootBoard.models || [rootBoard.model]) {
  modelKeys.add((manufacturer.trim() + '|' + model.trim()).replace(/\s+/g, ' ').toUpperCase());
}

function output(relative, content) {
  const file = path.join(root, relative);
  if (check) assert.equal(fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n'), content, relative + ' is stale; run node tools/generate-plugins.cjs');
  else fs.writeFileSync(file, content);
}

for (const entry of catalog.entries) {
  assert.match(entry.filename, /^[a-zA-Z0-9_]+_LHM_Temperatures\.js$/);
  assert.equal(filenames.has(entry.filename.toLowerCase()), false, 'duplicate plugin filename');
  filenames.add(entry.filename.toLowerCase());
  assert.equal(controllerIds.has(entry.controllerId), false, 'duplicate controller ID');
  controllerIds.add(entry.controllerId);
  for (const manufacturer of entry.manufacturers) for (const model of entry.models) {
    const key = (manufacturer.trim() + '|' + model.trim()).replace(/\s+/g, ' ').toUpperCase();
    assert.equal(modelKeys.has(key), false, 'ambiguous model match: ' + key);
    modelKeys.add(key);
  }
  const name = entry.vendor + ' ' + entry.models[0] + ' Temperatures';
  const board = { manufacturers: entry.manufacturers, model: entry.models[0], models: entry.models,
    controllerId: entry.controllerId, controllerName: name, variants: entry.variants };
  installEntries.push({ path: 'plugins/' + entry.filename, manufacturers: entry.manufacturers, models: entry.models });
  const source = catalog.sources.find(s => s.file === 'SuperIOHardware.cs').url + '#L' + entry.sourceLine;
  const header = '// Generated by tools/generate-plugins.cjs. Edit the shared runtime/catalog, then regenerate.\n' +
    '// Upstream-derived for LibreHardwareMonitorLib 0.9.6; hardware untested.\n' +
    '// Primary Super I/O only. Raw channel names must match before publishing.\n' +
    '// Source: ' + source + '\n// Mapping attribution: plugins/NOTICE.md (MPL-2.0).\n';
  const plugin = template.replace(/export function Name\(\) \{[^\n]*\}/, 'export function Name() { return ' + JSON.stringify(name + ' (LHM)') + '; }')
    .replace(/const BOARD = \{[\s\S]*?\n\};\n(?=const SENSOR_DEFINITIONS)/, 'const BOARD = ' + JSON.stringify(board, null, 4) + ';\n');
  assert.notEqual(plugin, template, 'template replacement failed');
  output('plugins/' + entry.filename, header + plugin);
  written++;
}
const actual = fs.readdirSync(path.join(root, 'plugins')).filter(f => f.endsWith('_LHM_Temperatures.js'));
assert.deepEqual(actual.map(f => f.toLowerCase()).sort(), [...filenames].sort(), 'unlisted or missing generated plugins');
output('plugins/install-manifest.json', JSON.stringify({ schemaVersion: 1, plugins: installEntries }, null, 2) + '\n');

const counts = Object.groupBy(catalog.entries, e => e.vendor);
let support = '# Motherboard plugins\n\n' +
  `There are **${catalog.entries.length + 1} plugins**: the original ASUS PRIME Z790-P WIFI plugin plus **${catalog.entries.length} upstream-derived plugins** below. ` +
  `The new plugins cover ${catalog.entries.reduce((sum, e) => sum + e.models.length, 0)} exact SMBIOS model strings, including aliases.\n\n` +
  'The new plugins are **hardware untested**. Their mappings come from the pinned LibreHardwareMonitorLib 0.9.6 tables, not probes of those boards. ' +
  'They require exact manufacturer/model matches, a primary Super I/O chip path, matching raw LHM channel names, and fresh valid readings. ' +
  'Chip alternatives reflect the upstream routing table; they do not certify that every chip is fitted to a board. ' +
  'Secondary Super I/O channels, generic/unknown/AUX labels, and unsupported embedded-controller-only boards are excluded. ' +
  'Where an upstream label occurs on two channels, the display names include channel numbers rather than silently selecting one.\n\n' +
  'The original [ASUS PRIME Z790-P WIFI plugin](../ASUS_LHM_Temperatures.js) has earlier native sensor validation; version 0.2 SignalRGB integration remains pending.\n\n' +
  '| Manufacturer | Additional plugins |\n|---|---:|\n' + Object.entries(counts).map(([vendor, entries]) => `| ${vendor} | ${entries.length} |`).join('\n') + '\n\n' +
  'The root installer detects the motherboard through Windows SMBIOS/CIM, installs only its matching plugin, and backs up other packaged plugins left by older installations. ' +
  'Unknown or ambiguous boards stop installation before service or plugin changes. You can also copy the relevant JS file into SignalRGB\'s Plugins directory manually. ' +
  '`install-manifest.json` contains installer-only identity metadata generated from the plugins. No catalog or JSON file is needed by the running service or plugins.\n\n';
for (const [vendor, entries] of Object.entries(counts)) {
  support += '## ' + vendor + '\n\n| Exact SMBIOS model names / aliases | Plugin | Source |\n|---|---|---|\n';
  for (const entry of entries) support += '| ' + entry.models.map(m => '`' + m + '`').join('<br>') + ' | [' + entry.filename + '](' + entry.filename + ') | [LHM table](' + catalog.sources[0].url + '#L' + entry.sourceLine + ') |\n';
  support += '\n';
}
support += '## Regeneration\n\nRun `Build.ps1`, then `powershell.exe -NoProfile -ExecutionPolicy Bypass -File .\\tools\\Generate-Plugins.ps1`. ' +
  'The extractor checks SHA-256 hashes of the pinned upstream source, evaluates only model-specific table routes against a fake chip, and rejects hardware operations. ' +
  'The generated JS files embed their own board data and a copy of the runtime from the root ASUS plugin. ' +
  'Use `node tools/generate-plugins.cjs --check` to check generated files without downloading sources or opening hardware. ' +
  'The catalog records source hashes and exact model/manufacturer aliases validated against the compiled library. See [NOTICE.md](NOTICE.md).\n';
output('plugins/README.md', support);
console.log((check ? 'Verified ' : 'Generated ') + written + ' motherboard plugins and the support matrix.');
